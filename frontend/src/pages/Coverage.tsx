import { useState } from 'react'
import { Link, useSearchParams } from 'react-router-dom'
import { Badge } from '../animations/primitives'
import { domainMastery, useProgress } from '../hooks/useProgress'
import { EXAMS, coverage, findObjective, lessonForObjective, registries } from '../services/curriculum'
import type { ExamSlug } from '../services/types'

export default function Coverage() {
  const [params, setParams] = useSearchParams()
  const exam = (params.get('exam') as ExamSlug) || 'az-104'
  const [onlyMissing, setOnlyMissing] = useState(false)
  const { data } = useProgress()
  const c = coverage.exams[exam]
  const pct = (n: number) => (c && c.total ? Math.round((100 * n) / c.total) : 0)
  return (
    <div className="space-y-4">
      <h1 className="text-2xl font-semibold">Coverage audit</h1>
      <p className="text-sm text-slate-500">Generated by <code>scripts/validate_coverage.py</code> at {new Date(coverage.generatedAt).toLocaleString()}. Content coverage (does the platform teach and assess it?) is tracked separately from your mastery (do you know it?).</p>
      {coverage.errors.length > 0 && <div className="card border-red-300 p-3 text-sm text-red-700" role="alert">{coverage.errors.length} integrity error(s): {coverage.errors.join('; ')}</div>}
      <div className="flex flex-wrap gap-2" role="tablist">
        {EXAMS.map((e) => <button key={e} role="tab" aria-selected={e === exam} type="button" className={e === exam ? 'btn-primary' : 'btn-ghost'} onClick={() => setParams({ exam: e })}>{registries[e].examCode}</button>)}
      </div>
      {c && (
        <>
          <div className="grid gap-3 sm:grid-cols-3 lg:grid-cols-6">
            {[
              ['Published objectives', c.total],
              ['Content complete', c.complete],
              ['With complete lesson', c.withLesson],
              ['With tested animation', c.withTestedAnimation],
              ['With assessments', c.withAssessment],
              ['Awaiting human review', c.unverified],
            ].map(([label, n]) => (
              <div key={label} className="card p-3"><p className="label">{label}</p><p className="text-2xl font-semibold">{n}</p>{label !== 'Published objectives' && <p className="text-xs text-slate-500">{label === 'Awaiting human review' ? 'lessons not yet human-verified' : `${pct(n as number)}% of objectives`}</p>}</div>
            ))}
          </div>
          {c.complete < c.total && <p className="text-sm text-amber-700 dark:text-amber-300">{c.total - c.complete} objective(s) are missing content. The validator exits with a failure until they are covered.</p>}
          <section className="card p-4">
            <h2 className="mb-2 font-semibold">Your mastery by domain</h2>
            <ul className="space-y-1 text-sm">
              {domainMastery(data, exam).map((d) => (
                <li key={d.id} className="flex items-center gap-2">
                  <span className="flex-1">{d.name} <span className="text-slate-500">({d.weight})</span></span>
                  <span className="text-xs text-slate-500">{d.assessed}/{d.total} assessed</span>
                  {d.mastery === null ? <Badge tone="muted">no evidence</Badge> : <Badge tone={d.mastery < 70 ? 'deny' : 'allow'}>{d.mastery}%</Badge>}
                </li>
              ))}
            </ul>
          </section>
          <label className="flex items-center gap-2 text-sm"><input type="checkbox" checked={onlyMissing} onChange={(e) => setOnlyMissing(e.target.checked)} /> Show only objectives with missing content</label>
          <div className="overflow-x-auto">
            <table className="card w-full text-xs">
              <thead><tr className="text-left"><th className="p-2">Objective</th><th className="p-2">Lesson</th><th className="p-2">Animation</th><th className="p-2">Questions</th><th className="p-2">Lab</th><th className="p-2">Docs</th><th className="p-2">Verification</th><th className="p-2">Missing</th></tr></thead>
              <tbody>
                {c.entries.filter((e) => !onlyMissing || !e.complete).map((e) => {
                  const l = lessonForObjective(e.objectiveId)
                  const yes = (v: boolean | null) => (v === null ? '—' : v ? '✅' : '❌')
                  return (
                    <tr key={e.objectiveId} className="border-t border-slate-200 dark:border-slate-800">
                      <td className="p-2"><span className="font-mono">{e.objectiveId}</span> {l ? <Link className="underline" to={`/lesson/${l.id}`}>{findObjective(e.objectiveId)?.objective.text}</Link> : findObjective(e.objectiveId)?.objective.text}</td>
                      <td className="p-2">{yes(e.lesson)}</td><td className="p-2">{yes(e.animation)}</td><td className="p-2">{yes(e.assessment && e.appliedAssessment)}</td>
                      <td className="p-2">{yes(e.lab)}</td><td className="p-2">{yes(e.docs)}</td><td className="p-2">{e.verification ?? '—'}</td>
                      <td className="p-2 text-red-700 dark:text-red-400">{e.missing.join(', ')}</td>
                    </tr>
                  )
                })}
              </tbody>
            </table>
          </div>
        </>
      )}
    </div>
  )
}
